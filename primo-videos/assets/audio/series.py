#!/usr/bin/env python3
"""serie · soundtrack for a series: fixed identity + variation per seed.

In a series (e.g. 12 tutorials of the same app) the musical identity is decided once
(identity.json: style, timbres, BPM range, allowed modes and keys). Each piece gets ITS OWN
soundtrack, generated by arrange_series.py from variacao(identidade, semente). Never the
same soundtrack stretched.

    import series as serie
    ident = serie.carregar_identidade('identity.json')
    v = serie.variacao(ident, 4242)       # deterministic dict (key, bpm, mode, progression, motif, groove…)

CLI:
    python series.py --show identity.json SEMENTE          prints the variation
    python series.py --test identity.json [N]               checks the distinction rules on seeds 1..N
                                                               (default: the identity's guaranteed window)
    python series.py --compare folhaA.json folhaB.json [wavA wavB]
        musical differences + chroma similarity per bar (0–1). Exit code 0 if the pieces
        are distinct (similarity < 0.85) or, with the same seed, if the WAVs are identical.

Guarantees of variacao():
    - (key, bpm) comes from a bijection seed → pair: seeds whose difference is not a multiple of
      len(tons)·len(bpms) never repeat the pair, and neighboring seeds never repeat the key;
    - the progression (loop of degrees with rotation × harmonic rhythm × anticipation) comes from another bijection
      over 288–384 combinations per mode; the motif is generated by the seed's generator.
"""
