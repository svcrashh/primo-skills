#!/usr/bin/env node
// Escreve scenes/NN-nome/tempos.js de cada cena a partir da narration.json: em('palavra'), ate('palavra'), FIM_FALA,
// VOZ_EM e DURACAO_MINIMA, no relógio da cena. As cenas leem os tempos daqui, nunca de número copiado.
//   node tempos.mjs <project> [--narration voice/v1/narration.json] [--speech-at 1.4] [--exit 0.5]
// A fala "abertura" vai para a cena 00-…, { capitulo: n } para a NN-…, "fechamento" para a 99-…. --speech-at é o mesmo
// do assemble.mjs (início da cena + speech-at). Rode de novo sempre que a voz mudar e renderize as cenas de novo.
// em() acha a PALAVRA EXATA, sem acento, caixa nem pontuação: em('nove') não pega "noventa" (pegava, num em() antigo por
// prefixo, e o preço pulava 0,5 s antes do "nove!"). Também vale: em('acme') para "acme.app!" (o pedaço antes do
// ponto), em('quarenta e dois') (a sequência) e em('nove', 2) (a 2ª vez).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export function limpa(s) {
  return String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9$]/g, '')
}

// Índice da `vez`-ésima ocorrência de `busca` em `palavras` ([{ texto }]), ou -1. Uma palavra casa quando é igual à
// busca ou quando o seu primeiro pedaço (antes de ponto, hífen, barra) é igual: "acme.app!" casa com "acme".
export function acharPalavra(palavras, busca, vez = 1) {
  const pedaco = (t) => limpa(String(t).split(/[./\-–—:]/).filter((x) => limpa(x))[0] || t)
  const b = String(busca).trim().split(/\s+/).map(limpa).filter(Boolean)
  if (!b.length) return -1
  let k = 0
  for (let i = 0; i + b.length <= palavras.length; i++) {
    const ok = b.every((x, j) => limpa(palavras[i + j].texto) === x || pedaco(palavras[i + j].texto) === x)
    if (ok && ++k === vez) return i
  }
  return -1
}

// O em() antigo, por prefixo, só para diagnosticar cenas escritas com ele (scripts/refine/cenas.mjs).
export function acharPorPrefixo(palavras, busca, vez = 1) {
  const b = limpa(busca)
  let k = 0
  return palavras.findIndex((p) => limpa(p.texto).startsWith(b) && ++k === vez)
}

export const r3 = (v) => Math.round(v * 1000) / 1000
export const numeroDaCena = (f) => (f.onde === 'abertura' ? 0 : f.onde === 'fechamento' ? 99 : f.onde?.capitulo)

// A narration.json do projeto: o --narration, ou a única voice/*/narration.json que existir.
export function acharLocucao(projeto, arg) {
  if (arg) return path.resolve(projeto, arg)
  const dir = path.join(projeto, 'voice')
  const achados = fs.existsSync(dir) ? fs.readdirSync(dir).filter((v) => !v.startsWith('_') && fs.existsSync(path.join(dir, v, 'narration.json'))) : []
  if (achados.length === 1) return path.join(dir, achados[0], 'narration.json')
  throw new Error(achados.length ? `there is more than one narration (${achados.map((v) => `voice/${v}`).join(', ')}): say which with --narration voice/<version>/narration.json` : `could not find voice/<version>/narration.json in ${projeto}`)
}

export function temposJs(fala, { falaEm, saida, origem }) {
  const fim = fala.palavras.at(-1).fim
  const minimo = Math.ceil((falaEm + fim + saida) * 10) / 10
  const dados = { id: fala.id, texto: fala.texto, inicio_voz: fala.inicio_voz, palavras: fala.palavras.map((p) => ({ texto: p.texto, ini: r3(p.ini), fim: r3(p.fim) })) }
  return { minimo, js: `// Generated by scripts/chapters/tempos.mjs from ${origem}. Do not edit: run it again if the voice changes.
// Times on the scene clock (the line starts at VOZ_EM). Minimum duration of this scene: ${minimo} s.
const VOZ_EM = ${falaEm}
const FALA = ${JSON.stringify(dados)}
const FIM_FALA = VOZ_EM + FALA.palavras[FALA.palavras.length - 1].fim
const DURACAO_MINIMA = ${minimo}
${limpa.toString()}
${acharPalavra.toString()}
function _palavra(busca, vez = 1) {
  const i = acharPalavra(FALA.palavras, busca, vez)
  if (i < 0) console.error(\`WORD "\${busca}" (time \${vez}) IS NOT IN LINE \${FALA.id}: \${FALA.texto}\`)
  return Math.max(0, i)
}
// When the word starts (em) and ends (ate), on the scene clock: em('forty'), ate('nine', 2).
const em = (busca, vez) => VOZ_EM + FALA.palavras[_palavra(busca, vez)].ini
const ate = (busca, vez) => VOZ_EM + FALA.palavras[_palavra(busca, vez)].fim
` }
}

export function escreverTempos(projeto, { locucao, falaEm = 1.4, saida = 0.5, log = console.log } = {}) {
  const arq = acharLocucao(projeto, locucao)
  const loc = JSON.parse(fs.readFileSync(arq, 'utf8'))
  // a cena de exemplo do molde (01-example) nunca recebe a fala: o capítulo 1 é o 01-… de verdade
  const cenas = fs.readdirSync(path.join(projeto, 'scenes')).filter((c) => /^\d\d-/.test(c) && !/-example$/.test(c))
  const feitas = []
  for (const f of loc.falas) {
    const nn = String(numeroDaCena(f)).padStart(2, '0')
    const cena = cenas.find((c) => c.startsWith(nn + '-'))
    const { minimo, js } = temposJs(f, { falaEm, saida, origem: path.relative(projeto, arq) })
    if (!cena) { log(`  ${f.id}: the folder scenes/${nn}-… is missing (minimum duration ${minimo} s)`); continue }
    fs.writeFileSync(path.join(projeto, 'scenes', cena, 'tempos.js'), js)
    // a cena do molde não carrega o tempos.js: entra antes do scene.js, que é quem usa o em()
    const html = path.join(projeto, 'scenes', cena, 'index.html')
    if (fs.existsSync(html)) {
      const h = fs.readFileSync(html, 'utf8')
      if (!/src="tempos\.js"/.test(h) && /<script src="scene\.js"><\/script>/.test(h)) fs.writeFileSync(html, h.replace('<script src="scene.js"></script>', '<script src="tempos.js"></script>\n<script src="scene.js"></script>'))
    }
    feitas.push({ cena, id: f.id, minimo })
    log(`✓ scenes/${cena}/tempos.js · ${f.id} · line ${r3(f.palavras.at(-1).fim)} s · scene ≥ ${minimo} s`)
  }
  return feitas
}

// caminho real dos dois lados: a skill é instalada por link simbólico, e aí o argv[1] não bate com o import.meta.url
if (process.argv[1] && (() => { try { return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url)) } catch { return false } })()) {
  const args = process.argv.slice(2)
  const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d }
  const proj = args.find((a, i) => !a.startsWith('--') && !(i > 0 && args[i - 1].startsWith('--')))
  if (!proj) { console.error('usage: node tempos.mjs <project> [--narration voice/v1/narration.json] [--speech-at 1.4] [--exit 0.5]'); process.exit(2) }
  try { escreverTempos(path.resolve(proj), { locucao: opt('narration'), falaEm: +opt('speech-at', 1.4), saida: +opt('exit', 0.5) }) } catch (e) { console.error(e.message); process.exit(1) }
}
