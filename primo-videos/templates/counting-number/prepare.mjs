#!/usr/bin/env node
// Monta a pasta de um vídeo do molde "número que conta" a partir de um arquivo de parâmetros.
//   node prepare.mjs <parametros.json> <video-folder> [--narration voice/pt/narration.json]
// Sem --narration: copia o molde, baixa as fontes, escreve params.js, voice/script.json (quando há falas, para o passo
// de voz da skill gerar a locução antes do render) e a trilha sem voz: audio/sheet.json (seções, whoosh em cada
// troca de bloco) e audio/identity.json com papel protagonista.
// Com --narration: põe a duração e as palavras de cada fala nos blocos (legenda palavra a palavra), e escreve
// audio/voz.wav, audio/sheet.json (com o bloco "voz": a trilha cede à fala) e audio/identity.json.
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { execFileSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'

const AQUI = path.dirname(fileURLToPath(import.meta.url))
const SKILL = path.resolve(AQUI, '..', '..')
const args = process.argv.slice(2)
const opt = (k) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : null }
const [arqParams, pastaArg] = args.filter((a, i) => !a.startsWith('--') && !(i > 0 && args[i - 1].startsWith('--')))
if (!arqParams || !pastaArg) { console.error('usage: node prepare.mjs <parametros.json> <video-folder> [--narration voice/pt/narration.json]'); process.exit(1) }
const pasta = path.resolve(pastaArg)
const P = JSON.parse(fs.readFileSync(arqParams, 'utf8'))
const base = path.dirname(path.resolve(arqParams))
fs.mkdirSync(path.join(pasta, 'media'), { recursive: true })

for (const f of ['index.html', 'video.js', 'template.js']) fs.copyFileSync(path.join(AQUI, f), path.join(pasta, f))
fs.copyFileSync(path.join(SKILL, 'assets', 'template', 'engine.js'), path.join(pasta, 'engine.js'))

if (P.marca.logo) {
  const src = path.resolve(base, P.marca.logo), dst = 'media/' + path.basename(src)   // URL da página: barra normal também no Windows
  fs.copyFileSync(src, path.join(pasta, dst))
  P.marca.logo = dst
}
if (P.marca.simbolo) {   // o símbolo gigante do fundo (opcional): o PNG da marca, copiado como está
  const src = path.resolve(base, P.marca.simbolo.arquivo), dst = 'media/' + path.basename(src)
  fs.copyFileSync(src, path.join(pasta, dst))
  P.marca.simbolo.arquivo = dst
}

const familias = [...new Set([P.marca.fontes.numero.familia, P.marca.fontes.texto.familia, (P.marca.fontes.etiqueta || P.marca.fontes.texto).familia])]
const css = path.join(pasta, 'fonts', 'fonts.css')
const temTodas = fs.existsSync(css) && familias.every((f) => fs.readFileSync(css, 'utf8').includes(`"${f}"`))
if (!temTodas) execFileSync(process.execPath, [path.join(SKILL, 'scripts', 'fonts.mjs'), pasta, ...familias], { stdio: 'inherit' })

// falas: { texto, em } em cada bloco; id b1, b2… pela posição do bloco
const emPadrao = (b) => (b.tipo === 'contador' ? (b.sozinho ?? 1.6) + 0.25 : 0.45)
P.blocos.forEach((b, i) => { if (typeof b.fala === 'string') b.fala = { texto: b.fala }; if (b.fala) { b.fala.id = `b${i + 1}`; b.fala.em ??= emPadrao(b) } })
const comFala = P.blocos.filter((b) => b.fala)
const narra = fs.existsSync(path.join(SKILL, 'scripts', 'tutorial', 'locucao.mjs'))   // os níveis da skill com narração
if (comFala.length && !narra && !opt('narration')) console.log('this copy of the skill has no voice module (scripts/tutorial/locucao.mjs is missing): the "falas" in the JSON are left out and the soundtrack is the lead.')

const loc = opt('narration') ? path.resolve(opt('narration')) : null
if (loc && !narra) { console.error(`this video has a voiceover (${loc}), but this copy of the skill has no voice module (scripts/tutorial/locucao.mjs is missing): reinstall the skill.`); process.exit(1) }
if (loc) {
  const L = JSON.parse(fs.readFileSync(loc, 'utf8'))
  for (const b of comFala) {
    const f = L.falas.find((x) => x.id === b.fala.id)
    if (!f) throw new Error(`the voiceover has no line ${b.fala.id} ("${b.fala.texto}"): generate the voice again`)
    if (f.texto !== b.fala.texto) throw new Error(`line ${b.fala.id} changed since the voiceover ("${f.texto}" → "${b.fala.texto}"): generate the voice again`)
    const iv = f.inicio_voz || 0
    b.fala.dur = +(f.palavras[f.palavras.length - 1].fim - iv).toFixed(3)
    b.fala.palavras = f.palavras.map((w) => ({ texto: w.texto, ini: +(w.ini - iv).toFixed(3), fim: +(w.fim - iv).toFixed(3) }))
    b.fala._arquivo = path.resolve(path.dirname(loc), f.arquivo)
    b.fala._iv = iv
  }
}

const paramsJs = `// generated by prepare.mjs from ${path.basename(arqParams)} — edit the JSON, not this file\nconst PARAMS = ${JSON.stringify(P, (k, v) => (k.startsWith('_') ? undefined : v), 2)}\n`
fs.writeFileSync(path.join(pasta, 'params.js'), paramsJs, 'utf8')

// roteiro de locução (Contrato da skill: references/voz-locucao.md §6)
if (comFala.length && P.voz && narra) {
  fs.mkdirSync(path.join(pasta, 'voice'), { recursive: true })
  const roteiro = { idioma: P.idioma || 'en-US', perfil: P.voz.perfil || 'reels', voz: { id: P.voz.id, nome: P.voz.nome, modelo: P.voz.modelo || 'eleven_multilingual_v2' },
    ...(P.voz.ajustes ? { ajustes: P.voz.ajustes } : {}), pronuncia: P.voz.pronuncia || {},
    falas: comFala.map((b) => ({ id: b.fala.id, onde: { passo: P.blocos.indexOf(b) + 1 }, texto: b.fala.texto })) }
  fs.writeFileSync(path.join(pasta, 'voice', 'script.json'), JSON.stringify(roteiro, null, 2) + '\n', 'utf8')
}

// a mesma linha do tempo do navegador (video.js), rodada aqui
const ctx = { PARAMS: JSON.parse(JSON.stringify(P)), Math, console }
vm.createContext(ctx)
vm.runInContext(fs.readFileSync(path.join(AQUI, 'video.js'), 'utf8') + '\n;this.LINHA = LINHA; this.VIDEO = VIDEO', ctx)
const { LINHA, VIDEO } = ctx
console.log(`duration ${VIDEO.duracao} s · ` + LINHA.map((b) => `${b.tipo} ${b.t0.toFixed(2)}–${b.t1.toFixed(2)}`).join(' · '))
const falado = comFala.reduce((s, b) => s + (b.fala.dur || 0), 0)
if (loc) console.log(`voice speaks ${falado.toFixed(1)} s of ${VIDEO.duracao} s (${Math.round((100 * falado) / VIDEO.duracao)}%)`)

// trilha: com a locução, a folha leva o bloco "voz" (a trilha cede à fala); sem ela, a trilha é a protagonista
fs.mkdirSync(path.join(pasta, 'audio'), { recursive: true })
const L = loc ? await import(pathToFileURL(path.join(SKILL, 'scripts', 'tutorial', 'locucao.mjs')).href) : null
const falas = !loc ? [] : LINHA.filter((b) => b.fala).map((b) => {
  const src = comFala.find((x) => x.fala.id === b.fala.id).fala
  const som = b.t0 + b.fala.em
  return { id: b.fala.id, texto: b.fala.texto, caminho: src._arquivo, inicioArquivo: som - src._iv, som, fim: som + b.fala.dur }
})
if (loc) L.escreverVozWav(falas, VIDEO.duracao, path.join(pasta, 'audio', 'voz.wav'))
const folha = {
  titulo: VIDEO.titulo, duracao: VIDEO.duracao, bpm: 120, compasso: 4, taxa: 48000, saida: 'soundtrack.wav',
  loudness_lufs: -14.0, teto_dbtp: -1.5, semente: P.trilha?.semente ?? 7, silencios: [], fade: [Math.max(0, VIDEO.duracao - 0.8), VIDEO.duracao],
  secoes: LINHA.map((b, i) => ({ nome: i === 0 ? 'abertura' : b.i === LINHA.length - 1 ? 'fechamento' : `${b.tipo}-${i + 1}`, de: +b.t0.toFixed(3), ate: +b.t1.toFixed(3), energia: 'media' })),
  marcos: LINHA.slice(1).map((b) => ({ t: +b.t0.toFixed(3), evento: `enters ${b.tipo}`, som: 'whoosh', opcional: true })),
  ...(loc ? { voz: L.blocoFolha(falas, P.voz?.perfil || 'reels') } : {}),
}
fs.writeFileSync(path.join(pasta, 'audio', 'sheet.json'), JSON.stringify(folha, null, 1) + '\n', 'utf8')
const ident = { versao: 2, nome: `${P.marca.nome} · number that counts`, papel: loc ? 'fundo' : 'protagonista', loudness_lufs: -14.0, densidade: 'baixa', ...(P.trilha?.identidade || {}) }
fs.writeFileSync(path.join(pasta, 'audio', 'identity.json'), JSON.stringify(ident, null, 2) + '\n', 'utf8')
if (loc) fs.writeFileSync(path.join(pasta, 'legenda.srt'), L.srt(falas), 'utf8')
console.log(`done: ${pasta}`)
