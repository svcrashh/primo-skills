#!/usr/bin/env node
// Renderiza o molde "checklist que marca" a partir de um arquivo de parâmetros.
//   node render.mjs <params.json> --out <folder> [--name x] [--formats 16x9,9x16] [--mode final|draft]
//                       [--no-sound] [--assemble-only] [-- <opções do render.cjs, ex. --sub 4>]
//        formatos: 16x9, 19x9, 21x9, 9x16, 1x1, 4x5
// Monta <output>/.work-<name>/ (cena, engine.js da skill, params.js, fontes, logo), confere a cena no Chromium (erro de
// parâmetro ou lista que não cabe para aqui, com o que fazer), compõe a trilha da skill como protagonista (um "blip"
// que sobe a cada ✓, um toque firme a cada ✕, um acento quando o logo entra), renderiza cada formato, junta e confere
// a entrega (scripts/finalize.mjs) e tira a folha de quadros.
// Sai <output>/<name>-<format>.mp4 e <output>/<name>-<format>-sheet.png. OLHE as folhas.
// Fontes sem rede: rode antes `node scripts/example-fonts.mjs <output>/.work-<name>` (a Inter dos exemplos); outra família vem
// do scripts/fonts.mjs. Prévia: <output>/.work-<name>/index.html?f=9x16&t=4.2 (ou ?play).
// --assemble-only: só monta a obra (sem navegador, sem som, sem render). --no-sound: vídeo mudo.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync, execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { acharPython } from '../../scripts/where.cjs'
import { aberturaDoJson, relatar } from '../../scripts/opening.mjs'

const AQUI = path.dirname(fileURLToPath(import.meta.url))
const SKILL = path.resolve(AQUI, '..', '..')
const require = createRequire(import.meta.url)
const { planejarChecklist } = require(path.join(AQUI, 'scene', 'plan.js'))

const todos = process.argv.slice(2), corte = todos.indexOf('--')
const args = corte >= 0 ? todos.slice(0, corte) : todos, extra = corte >= 0 ? todos.slice(corte + 1) : []
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d }
const tem = (k) => args.includes('--' + k)
const exp = (p) => (p && p.startsWith('~') ? path.join(os.homedir(), p.slice(1)) : p)
const arq = args[0] && !args[0].startsWith('--') ? path.resolve(exp(args[0])) : null
const USO = 'usage: node render.mjs <params.json> --out <folder> [--name x] [--formats 16x9,9x16] [--mode final|draft] [--no-sound] [--assemble-only]'
if (!arq || !opt('out')) { console.error(USO); process.exit(1) }
if (!fs.existsSync(arq)) { console.error(`file not found: ${arq}`); process.exit(1) }

// escala de cada quadro e grade da folha, por formato (o 19:9 e o 21:9 guardam a altura do 16:9)
const FOLHA = { '16x9': ['480:-1', '6x4'], '19x9': ['570:-1', '6x4'], '21x9': ['630:-1', '6x4'], '9x16': ['270:-1', '8x3'], '1x1': ['360:-1', '6x4'], '4x5': ['324:-1', '6x4'] }
const P = JSON.parse(fs.readFileSync(arq, 'utf8'))
const formatos = opt('formats', (P.formatos || ['16x9']).join(',')).split(',').filter(Boolean)
const semFolha = formatos.filter((f) => !FOLHA[f])
if (semFolha.length) { console.error(`format this template doesn't support: ${semFolha.join(', ')}. Use ${Object.keys(FOLHA).join(', ')}.`); process.exit(1) }
let plano
try { plano = planejarChecklist(P) } catch (e) { console.error(e.message); process.exit(1) }

const base = path.dirname(arq)
const nome = opt('name', P.nome || path.basename(arq, '.json'))
const saida = path.resolve(exp(opt('out')))
const obra = path.join(saida, `.work-${nome}`)
const modo = opt('mode', 'final')

// 1. a cena e o motor da skill
fs.mkdirSync(path.join(obra, 'media'), { recursive: true })
for (const f of ['index.html', 'plan.js', 'video.js', 'checklist.js']) fs.copyFileSync(path.join(AQUI, 'scene', f), path.join(obra, f))
fs.copyFileSync(path.join(SKILL, 'assets', 'template', 'engine.js'), path.join(obra, 'engine.js'))

// 2. mídia: o logo (PNG, a proporção vem do arquivo) vai para media/
const copia = (src, onde) => {
  const abs = path.resolve(base, exp(src))
  if (!fs.existsSync(abs)) { console.error(`MISSING IMAGE (${onde}): ${src} (looked in ${abs})`); process.exit(1) }
  const dst = `media/${path.basename(abs)}`   // o caminho que a página lê: com /, também no Windows
  fs.copyFileSync(abs, path.join(obra, dst))
  return dst
}
P.marca.logo = copia(P.marca.logo, 'marca.logo')
const png = fs.readFileSync(path.join(obra, P.marca.logo))
if (png.toString('ascii', 1, 4) !== 'PNG') { console.error(`marca.logo is not a real PNG: ${P.marca.logo}`); process.exit(1) }
P.marca.logoAspecto = png.readUInt32BE(16) / png.readUInt32BE(20)
fs.writeFileSync(path.join(obra, 'params.js'), `// generated by render.mjs from ${path.basename(arq)}: edit the JSON, not this file\nconst PARAMS = ${JSON.stringify(P, null, 1)}\n`)

// 3. fontes dentro da obra (sem rede no render)
const familias = [...new Set([P.marca.fontes.texto, P.marca.fontes.titulo].filter(Boolean))]
const css = path.join(obra, 'fonts', 'fonts.css')
if (!fs.existsSync(css) || familias.some((f) => !fs.readFileSync(css, 'utf8').includes(`"${f}"`))) {
  const r = spawnSync(process.execPath, [path.join(SKILL, 'scripts', 'fonts.mjs'), obra, ...familias], { stdio: 'inherit' })
  if (r.status !== 0) { console.error(`the fonts did not load (${familias.join(', ')}): see the message above`); process.exit(1) }
}
console.log(`plan · ${plano.estrutura} · camera ${plano.camera} · transition ${plano.transicao} · ${plano.total} items · ${plano.dur} s`)
for (const m of plano.marcas) console.log(`  ${m.t.toFixed(2).padStart(6)} ${m.marca === 'ok' ? '✓' : '✕'} ${typeof plano.grupos[m.g].itens[m.k] === 'string' ? plano.grupos[m.g].itens[m.k] : plano.grupos[m.g].itens[m.k].t}`)
console.log(`  ${plano.tSai.toFixed(2).padStart(6)} closing (only the logo, comes in at ${plano.tLogo.toFixed(2)})`)
if (tem('assemble-only')) { console.log(`assembled: ${obra}`); process.exit(0) }

// 4. a cena no Chromium, em cada formato: erro no console (parâmetro, lista que não cabe, fonte) para aqui
const { abrirNavegador } = require(path.join(SKILL, 'scripts', 'playwright.cjs'))
{
  const { browser } = await abrirNavegador(obra)
  const erros = []
  for (const f of formatos) {
    const pg = await browser.newPage()
    pg.on('console', (m) => { if (m.type() === 'error') erros.push(`${f}: ${m.text()}`) })
    pg.on('pageerror', (e) => erros.push(`${f}: ${e.message}`))
    await pg.goto(pathToFileURL(path.join(obra, 'index.html')).href + `?f=${f}`)
    await pg.waitForFunction('window.__ready === true', null, { timeout: 60000 }).catch(() => erros.push(`${f}: the scene was not ready within 60 s`))
    await pg.close()
  }
  await browser.close()
  if (erros.length) { console.error('SCENE ERROR:\n' + [...new Set(erros)].join('\n')); process.exit(3) }
}

// 5. a trilha da skill, protagonista (sem voz), com os sons da cena como marcos
let comTrilha = false
if (!tem('no-sound')) {
  const py = acharPython()
  if (!py) console.error(`WARNING: without Python with numpy and scipy, the video comes out silent. Run once: node ${path.join(SKILL, 'scripts', 'environment.mjs')} --fix`)
  else {
    const dirAudio = path.join(obra, 'audio')
    fs.mkdirSync(dirAudio, { recursive: true })
    fs.rmSync(path.join(dirAudio, 'soundtrack.wav'), { force: true })
    const r3 = (x) => +x.toFixed(3)
    const marcos = plano.sons.map((s) => ({ t: r3(s.t), evento: s.som, som: s.som, ...(s.som === 'acento' ? {} : { efeito: s.som }), ...(s.passo != null ? { passo: s.passo } : {}), ...(s.variante ? { variante: s.variante } : {}), opcional: !!s.opcional }))
    const folha = { titulo: `${P.marca.nome} · ticking checklist`, duracao: plano.dur, bpm: 120, compasso: 4, taxa: 48000, saida: 'soundtrack.wav',
      loudness_lufs: -14.0, teto_dbtp: -1.5, semente: P.trilha?.semente ?? 7, silencios: [], fade: [r3(plano.dur - 0.8), plano.dur],
      secoes: plano.secoes.map((s) => ({ nome: s.nome, de: r3(s.de), ate: r3(s.ate), energia: 'media' })), marcos }
    const ident = { versao: 2, nome: `${P.marca.nome} · ticking checklist`, papel: 'protagonista', densidade: 'baixa', loudness_lufs: -14.0, bpm: [100, 112],
      modos: ['maior', 'mixolidio'], tons: ['C', 'D', 'F', 'G', 'A'],
      instrumentos: { harmonia: ['epiano', 'piano'], baixo: ['bass_note'], percussao: ['kick', 'clap', 'hat', 'shaker'], melodia: ['pluck'], textura: ['pad_note'] },
      ...(P.trilha?.identidade || {}) }
    if (!P.trilha?.identidade) console.log('soundtrack: no "trilha.identidade" in the JSON, using a neutral identity (declare the audience genre: assets/audio/API.md)')
    fs.writeFileSync(path.join(dirAudio, 'identity.json'), JSON.stringify(ident, null, 2) + '\n')
    for (const lufs of [-14, -16]) {
      folha.loudness_lufs = lufs
      fs.writeFileSync(path.join(dirAudio, 'sheet.json'), JSON.stringify(folha, null, 1) + '\n')
      const r = spawnSync(py, [path.join(SKILL, 'assets', 'audio', 'arrange_series.py'), 'identity.json', 'sheet.json'], { cwd: dirAudio, stdio: 'inherit' })
      if (r.status !== 0 || !fs.existsSync(path.join(dirAudio, 'soundtrack.wav'))) { console.error('the soundtrack was not created (see above); run with --no-sound for a silent video'); process.exit(1) }
      const v = spawnSync(py, [path.join(SKILL, 'assets', 'audio', 'verify.py'), 'sheet.json'], { cwd: dirAudio, encoding: 'utf8' })
      if (v.status === 0) { console.log(`soundtrack: verify.py all OK at ${lufs} LUFS (marks, loudness, peak)`); break }
      console.error(`soundtrack at ${lufs} LUFS failed verify.py:\n${(v.stdout || '').split('\n').filter((l) => /FAILED/.test(l)).join('\n')}`)
      if (lufs === -16) { console.error('WARNING: the soundtrack failed the check; read audio/sheet.json and run verify.py by hand'); process.exitCode = 1 }
    }
    comTrilha = true
  }
}

// 6. render de cada formato, som junto e conferido, folha de quadros
for (const f of formatos) {
  const r = spawnSync(process.execPath, [path.join(SKILL, 'scripts', 'render.cjs'), '--project', obra, '--mode', modo, '--format', f, '--out', `out/${f}.mp4`, '--no-sheet', ...extra], { stdio: 'inherit' })
  if (r.status !== 0) { console.error(`✗ ${f}: render exited with code ${r.status}`); process.exitCode = 1; continue }
  const mudo = path.join(obra, 'out', `${f}.mp4`), final = path.join(saida, `${nome}-${f}.mp4`)
  if (comTrilha) {
    const v = spawnSync(process.execPath, [path.join(SKILL, 'scripts', 'finalize.mjs'), '--project', obra, '--video', `out/${f}.mp4`, '--audio', 'audio/soundtrack.wav', '--out', final],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 180000 })
    process.stdout.write(v.stdout || ''); process.stderr.write(v.stderr || '')
    if (v.status !== 0 && !/delivery verified\./.test(v.stdout || '')) { console.error(`✗ ${f}: finalizar flagged a problem in the delivery (above)`); process.exitCode = 1 }
  } else fs.copyFileSync(mudo, final)
  if (P.aberturaLogo) {   // o logo no começo (scripts/opening.mjs), antes da folha
    try { console.log(relatar(aberturaDoJson(final, P.aberturaLogo, path.dirname(path.resolve(arq))))) } catch (e) { console.error(`✗ ${f}: ${e.message}`); process.exitCode = 1 }
  }
  const dur = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', final]).toString().trim()
  const [escala, grade] = FOLHA[f]
  const folha = path.join(saida, `${nome}-${f}-sheet.png`)
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', final, '-vf', `fps=24/${dur},scale=${escala},tile=${grade}`, '-frames:v', '1', folha])
  console.log(`✓ ${final} · ${dur.toFixed(2)} s · LOOK at the sheet: ${folha}`)
}
