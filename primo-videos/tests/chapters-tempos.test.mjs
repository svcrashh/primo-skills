// com falas inventadas cujos tempos o teste conhece. node --test tests/chapters-tempos.test.mjs   (sem rede)
import { test, describe } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import vm from 'node:vm'
import { acharPalavra, acharPorPrefixo, temposJs, escreverTempos } from '../scripts/chapters/tempos.mjs'
import { checarCenas } from '../scripts/refine/cenas.mjs'

const fala = (pares, extra = {}) => ({ texto: pares.map((p) => p[0]).join(' '), inicio_voz: pares[0][1], palavras: pares.map(([texto, ini, fim]) => ({ texto, ini, fim })), ...extra })
// "No Vyrta, nove e noventa e nove! Uns dez reais a menos." (com os tempos já acertados pela voz)
const C2 = fala([['No', 0.2, 0.4], ['Vyrta,', 0.45, 0.95], ['nove', 1.5, 1.85], ['e', 1.9, 2.0], ['noventa', 2.05, 2.55], ['e', 2.6, 2.7], ['nove!', 2.75, 3.3],
  ['Uns', 3.8, 4.0], ['dez', 4.05, 4.35], ['reais', 4.4, 4.8], ['a', 4.85, 4.92], ['menos.', 4.97, 5.4]], { id: 'c2', onde: { capitulo: 2 } })
// "Não espere. Na dúvida e sem pressa, é só abrir o vyrta.app! Termina em segundos. Sim."
const FECHO = fala([['Não', 0.2, 0.4], ['espere.', 0.45, 0.9], ['Na', 1.4, 1.5], ['dúvida', 1.55, 1.9], ['e', 1.95, 2.0], ['sem', 2.05, 2.25], ['pressa,', 2.3, 2.7],
  ['é', 2.75, 2.8], ['só', 2.85, 3.0], ['abrir', 3.05, 3.3], ['o', 3.35, 3.4], ['vyrta.app!', 3.45, 4.3], ['Termina', 5.04, 5.4], ['em', 5.45, 5.55], ['segundos.', 5.6, 6.2], ['Sim.', 6.8, 7.1]],
{ id: 'fecho', onde: 'fechamento' })
const textos = (f) => f.palavras.map((p) => p.texto)
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'chapters-tempos-'))

describe('acharPalavra: the exact word, not the prefix', () => {
  test("em('nove', 2) is the \"nove!\" at the end, not \"noventa\" (the case that put the price 0.5 s early)", () => {
    assert.equal(textos(C2)[acharPorPrefixo(C2.palavras, 'nove', 2)], 'noventa')
    assert.equal(textos(C2)[acharPalavra(C2.palavras, 'nove', 2)], 'nove!')
    assert.equal(acharPalavra(C2.palavras, 'nove', 3), -1)
  })
  test("em('na'): by prefix the 1st was \"Não\"; exact, \"Na\" exists only once", () => {
    assert.equal(textos(FECHO)[acharPorPrefixo(FECHO.palavras, 'na')], 'Não')
    assert.equal(textos(FECHO)[acharPalavra(FECHO.palavras, 'na')], 'Na')
    assert.equal(acharPalavra(FECHO.palavras, 'na', 2), -1)
  })
  test('accent, case and punctuation do not matter; the domain matches by the name; the sequence matches whole', () => {
    assert.equal(textos(C2)[acharPalavra(C2.palavras, 'vyrta')], 'Vyrta,')
    assert.equal(textos(FECHO)[acharPalavra(FECHO.palavras, 'vyrta')], 'vyrta.app!')
    assert.equal(textos(FECHO)[acharPalavra(FECHO.palavras, 'vyrta.app')], 'vyrta.app!')
    assert.equal(textos(FECHO)[acharPalavra(FECHO.palavras, 'e', 2)], 'é')
    assert.equal(acharPalavra(C2.palavras, 'nove e noventa'), textos(C2).indexOf('nove'))
    assert.equal(acharPalavra(C2.palavras, 'e noventa e'), textos(C2).indexOf('e'))
  })
})

describe('the generated tempos.js', () => {
  test('em()/ate() on the scene clock, with the exact word, and flags the missing word in the console', () => {
    const { js, minimo } = temposJs(C2, { falaEm: 0.3, saida: 0.5, origem: 'voice/v1/narration.json' })
    assert.match(js, /^\/\/ Generated by scripts\/chapters\/tempos\.mjs from voice\/v1\/narration\.json/)
    const erros = [], ctx = vm.createContext({ console: { error: (m) => erros.push(m) } })
    vm.runInContext(js + ';this.r = { a: em("nove", 2), b: ate("nove"), c: DURACAO_MINIMA, d: em("nove", 3), e: em("dúvida") }', ctx)
    assert.equal(ctx.r.a, 0.3 + 2.75)
    assert.equal(ctx.r.b, 0.3 + 1.85)
    assert.equal(ctx.r.c, minimo)
    assert.equal(minimo, Math.ceil((0.3 + 5.4 + 0.5) * 10) / 10)
    assert.match(erros[0], /WORD "nove" \(time 3\) IS NOT IN LINE c2/)
    assert.match(erros[1], /WORD "dúvida"/)
  })
})

// O tempos.js de um em() antigo, por prefixo, reconstruído para o teste.
function temposPrefixo(f, falaEm) {
  return `const VOZ_EM = ${falaEm}
const FALA = ${JSON.stringify({ id: f.id, texto: f.texto, palavras: f.palavras })}
const _limpa = (s) => s.toLowerCase().normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').replace(/[^a-z0-9$]/g, '')
function palavra(busca, vez = 1) { const b = _limpa(busca); let k = 0; const i = FALA.palavras.findIndex((p) => _limpa(p.texto).startsWith(b) && ++k === vez); if (i < 0) console.error('WORD ' + busca); return Math.max(0, i) }
const em = (busca, vez) => VOZ_EM + FALA.palavras[palavra(busca, vez)].ini
const ate = (busca, vez) => VOZ_EM + FALA.palavras[palavra(busca, vez)].fim
`
}

describe('checarCenas: the animation lights up on the word the voice says', () => {
  function projeto({ cena, tempos, nome = '02-vyrta', dur = 5.2 }) {
    const p = tmp(), dir = path.join(p, 'scenes', nome)
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(path.join(dir, 'scene.js'), cena)
    fs.writeFileSync(path.join(dir, 'tempos.js'), tempos)
    return { p, montagem: { cenas: [{ nome, ini: 8.4, dur }] } }
  }
  test("em('nove', 2) with the prefix tempos.js: an error, 0.70 s before \"nove!\", and it says it took \"noventa\"", () => {
    const { p, montagem } = projeto({ cena: "cena(0, 5, () => (t) => { if (t > em('nove', 2)) pulo() })", tempos: temposPrefixo(C2, 0.3) })
    const { achados } = checarCenas(p, [C2], { montagem })
    const a = achados.find((x) => x.checagem === 'palavra')
    assert.equal(a.nivel, 'erro')
    assert.match(a.msg, /takes "noventa" by the prefix/)
    assert.match(a.msg, /0\.70 s before "nove!"/)
    assert.ok(Math.abs(a.tVideo - (8.4 + 0.3 + 2.05)) < 1e-9)
  })
  test("the same scene with the skill's tempos.js: nothing to point out", () => {
    const { p, montagem } = projeto({ cena: "cena(0, 5, () => (t) => { if (t > em('nove', 2)) pulo() })", tempos: temposJs(C2, { falaEm: 0.3, saida: 0.5, origem: 'x' }).js, dur: 6.4 })
    assert.deepEqual(checarCenas(p, [C2], { montagem }).achados, [])
  })
  test("the old fix (em('nove', 3) by prefix) lights up right, but warns that with the exact em() it is the 2nd", () => {
    const { p, montagem } = projeto({ cena: "x(em('nove', 3))", tempos: temposPrefixo(C2, 0.3), dur: 6.4 })
    const a = checarCenas(p, [C2], { montagem }).achados
    assert.equal(a.length, 1)
    assert.equal(a[0].nivel, 'aviso')
    assert.match(a[0].oque_fazer, /em\('nove', 2\)/)
  })
  test('a word after a pause with the raw alignment: the scene lights up before the voice', () => {
    const cru = structuredClone(FECHO)
    cru.palavras.find((p) => p.texto === 'Termina').ini = 4.3
    const { p, montagem } = projeto({ cena: "a(em('termina')); b(em('sim'))", tempos: temposJs(cru, { falaEm: 0.3, saida: 0.5, origem: 'x' }).js, nome: '99-closing', dur: 9 })
    const a = checarCenas(p, [FECHO], { montagem }).achados.filter((x) => x.checagem === 'palavra')
    assert.equal(a.length, 1)
    assert.match(a[0].msg, /em\('termina'\) lights up at .* 0\.74 s before "Termina" is heard/)
  })
  test('a scene that goes on long after the last word (2.1 s left over)', () => {
    const f = fala([['Termina', 0.2, 0.6], ['em', 0.65, 0.8], ['segundos.', 0.85, 1.5]], { id: 'c1', onde: { capitulo: 2 } })
    const { p, montagem } = projeto({ cena: '', tempos: temposJs(f, { falaEm: 0.3, saida: 0.5, origem: 'x' }).js, dur: 4.4 })
    const a = checarCenas(p, [f], { montagem }).achados
    assert.equal(a.length, 1)
    assert.equal(a[0].checagem, 'silencio-fim')
    assert.equal(a[0].nivel, 'erro')
  })
  test('the template example scene (01-example) is left out', () => {
    const { p, montagem } = projeto({ cena: "x(em('nove', 3))", tempos: temposPrefixo(C2, 0.3), nome: '01-example', dur: 6.4 })
    assert.deepEqual(checarCenas(p, [C2], { montagem }).achados, [])
  })
})

describe('escreverTempos', () => {
  test('finds the only narration, writes the tempos.js of each scene, loads it before scene.js, and refuses when there is more than one', () => {
    const p = tmp()
    for (const c of ['00-opening', '02-vyrta']) fs.mkdirSync(path.join(p, 'scenes', c), { recursive: true })
    fs.writeFileSync(path.join(p, 'scenes', '02-vyrta', 'index.html'), '<script src="video.js"></script>\n<script src="scene.js"></script>\n')
    fs.mkdirSync(path.join(p, 'voice', 'v1'), { recursive: true })
    const loc = { versao: 1, idioma: 'pt-BR', falas: [C2, { ...C2, id: 'c9', onde: { capitulo: 9 } }] }
    fs.writeFileSync(path.join(p, 'voice', 'v1', 'narration.json'), JSON.stringify(loc))
    const log = []
    const feitas = escreverTempos(p, { falaEm: 0.3, log: (m) => log.push(m) })
    assert.deepEqual(feitas.map((f) => f.cena), ['02-vyrta'])
    assert.ok(fs.existsSync(path.join(p, 'scenes', '02-vyrta', 'tempos.js')))
    const html = () => fs.readFileSync(path.join(p, 'scenes', '02-vyrta', 'index.html'), 'utf8')
    assert.match(html(), /<script src="tempos.js"><\/script>\n<script src="scene.js">/)
    escreverTempos(p, { falaEm: 0.3, log() {} })
    assert.equal(html().match(/tempos\.js/g).length, 1, 'does not duplicate the tag')
    assert.ok(log.some((l) => /the folder scenes\/09-… is missing/.test(l)))
    fs.mkdirSync(path.join(p, 'voice', 'v2'), { recursive: true })
    fs.writeFileSync(path.join(p, 'voice', 'v2', 'narration.json'), JSON.stringify(loc))
    assert.throws(() => escreverTempos(p, { log() {} }), /more than one narration/)
  })
})
